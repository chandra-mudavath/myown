-- =====================================================================
-- 2. IDENTITY
-- auth_accounts is the only table with credentials. Every account of
-- any kind has one user_profiles row. Kind tables hold only fields
-- specific to that kind.
-- =====================================================================

CREATE TABLE auth_accounts (
    id                  VARCHAR(36)  NOT NULL PRIMARY KEY,
    account_number      VARCHAR(20)  NOT NULL UNIQUE,   -- <number_prefix>-00000001
    email               VARCHAR(254) NOT NULL UNIQUE,
    password_hash       VARCHAR(512) NOT NULL,
    account_type        VARCHAR(30)  NOT NULL,
    is_active           BOOLEAN      NOT NULL DEFAULT TRUE,
    is_verified         BOOLEAN      NOT NULL DEFAULT FALSE,
    email_verified_at   TIMESTAMP,
    last_login_at       TIMESTAMP,
    failed_login_count  INTEGER      NOT NULL DEFAULT 0,
    locked_until        TIMESTAMP,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_auth_accounts_type FOREIGN KEY (account_type) REFERENCES account_types (code)
);

CREATE TABLE auth_sessions (
    id                  VARCHAR(36)  NOT NULL PRIMARY KEY,
    account_id          VARCHAR(36)  NOT NULL,
    session_token_hash  VARCHAR(256) NOT NULL UNIQUE,
    ip_address          VARCHAR(45),
    user_agent          TEXT,
    expires_at          TIMESTAMP    NOT NULL,
    revoked_at          TIMESTAMP,
    last_activity_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_auth_sessions_account FOREIGN KEY (account_id) REFERENCES auth_accounts (id) ON DELETE CASCADE
);
CREATE INDEX ix_auth_sessions_account_id ON auth_sessions (account_id);

CREATE TABLE auth_refresh_tokens (
