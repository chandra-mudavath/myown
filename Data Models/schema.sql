-- =====================================================================
-- 8b. MESSAGING
-- DIRECT = two internal members, GROUP = named internal group,
-- CASE = client + case team on one filing, QUERY = a client question.
-- case_id is set only when the conversation is about a filing.
-- Who may read or post is checked in the chat service. Nothing is
-- hard-deleted: a daily job sets hidden_at once hide_after passes, and
-- hidden threads stay here for audit.
-- =====================================================================

CREATE TABLE chat_threads (
    id                      VARCHAR(36)  NOT NULL PRIMARY KEY,
    thread_number           VARCHAR(20)  NOT NULL UNIQUE,   -- MSG-0000001
    kind                    VARCHAR(10)  NOT NULL,
    name                    VARCHAR(100),                   -- GROUP only
    case_id                 VARCHAR(36),                    -- set only when about a filing; required for CASE
    topic_id                INTEGER,                        -- QUERY only
    subject                 VARCHAR(150),                   -- QUERY only
    direct_key              VARCHAR(110) UNIQUE,            -- DIRECT only: "smallerId:largerId" or "smallerId:largerId:caseId"
    status                  VARCHAR(10)  NOT NULL DEFAULT 'open',
    owner_account_id        VARCHAR(36),                    -- QUERY: who handles it; NULL = unclaimed
    created_by_account_id   VARCHAR(36)  NOT NULL,
    last_message_at         TIMESTAMP,
    last_message_preview    VARCHAR(160),                   -- last client-visible message
    resolved_at             TIMESTAMP,
    resolved_by_account_id  VARCHAR(36),
    hide_after              TIMESTAMP,                      -- daily job hides the thread after this; NULL = stays visible
    hidden_at               TIMESTAMP,                      -- set by the job; kept for audit, not shown in portals
    created_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ct_case FOREIGN KEY (case_id) REFERENCES tax_filings (id) ON DELETE CASCADE,
    CONSTRAINT fk_ct_topic FOREIGN KEY (topic_id) REFERENCES chat_query_topics (id),
    CONSTRAINT fk_ct_owner FOREIGN KEY (owner_account_id) REFERENCES auth_accounts (id) ON DELETE SET NULL,
    CONSTRAINT fk_ct_creator FOREIGN KEY (created_by_account_id) REFERENCES auth_accounts (id),
    CONSTRAINT fk_ct_resolver FOREIGN KEY (resolved_by_account_id) REFERENCES auth_accounts (id) ON DELETE SET NULL,
    CONSTRAINT ck_ct_kind CHECK (kind IN ('DIRECT', 'GROUP', 'CASE', 'QUERY')),
    CONSTRAINT ck_ct_status CHECK (status IN ('open', 'resolved', 'closed')),
    CONSTRAINT ck_ct_shape CHECK (
        (kind = 'DIRECT' AND direct_key IS NOT NULL AND topic_id IS NULL)
     OR (kind = 'GROUP'  AND name IS NOT NULL AND topic_id IS NULL AND direct_key IS NULL)
     OR (kind = 'CASE'   AND case_id IS NOT NULL AND direct_key IS NULL AND topic_id IS NULL)
     OR (kind = 'QUERY'  AND topic_id IS NOT NULL AND subject IS NOT NULL AND direct_key IS NULL)
    )
);
CREATE INDEX ix_chat_threads_case ON chat_threads (case_id, kind);
CREATE INDEX ix_chat_threads_queue ON chat_threads (kind, status, owner_account_id);   -- unclaimed / my queries
CREATE INDEX ix_chat_threads_hide ON chat_threads (hidden_at, hide_after);             -- daily hiding job
