-- =====================================================================
-- UrTax schema — revision 2 target
-- Source of truth: Data Models/Final-Data-Model.md (revision 2)
-- Diagram:         Data Models/schema-map.html
--
-- This file describes the TARGET schema from revision 2, not the
-- database as it is today. The live database is still built by the
-- SQLAlchemy models in app/models/ plus the Alembic migrations. Use this
-- file to review the design, or to stand up the schema on another
-- database engine.
--
-- Portability rules used throughout:
--   * Plain types only: VARCHAR, INTEGER, BOOLEAN, DATE, TIMESTAMP,
--     DECIMAL, TEXT. No engine-specific types or auto-increment.
--   * Primary keys are VARCHAR(36) UUIDs generated by the app, as the
--     current models do. Every record shown in the UI also has its own
--     unique readable number (CLI-00000001, FLI_0000001, DOC-0000001, ...),
--     handed out from the id_sequences counters (section 0), never by
--     counting rows. URLs and foreign keys keep using the UUID. Lookup tables use INTEGER ids set explicitly in
--     the seed data at the end of this file.
--   * JSON columns are stored as TEXT. Swap to JSONB (PostgreSQL) or JSON
--     (MySQL 5.7+) if you want database-side JSON queries.
--   * Timestamps are stored in UTC. The app writes timezone-aware values.
--   * Value lists (status, filing_method, ...) use CHECK constraints, not
--     ENUM types.
--
-- Engine notes:
--   PostgreSQL : runs as-is. Optionally TIMESTAMP -> TIMESTAMPTZ,
--                TEXT JSON columns -> JSONB.
--   MySQL 8    : runs as-is (InnoDB). CHECK constraints are enforced from 8.0.16.
--                Consider TIMESTAMP -> DATETIME (TIMESTAMP stops at 2038).
--                TEXT columns carry no DEFAULT because MySQL rejects one.
--   SQLite     : runs as-is. Run PRAGMA foreign_keys = ON; per connection.
--   SQL Server : BOOLEAN -> BIT, TEXT -> NVARCHAR(MAX), TIMESTAMP ->
--                DATETIME2. SQL Server rejects multiple cascade paths, so
--                change some ON DELETE CASCADE to NO ACTION if it errors.
--   Oracle     : BOOLEAN -> NUMBER(1) (before 23c), TEXT -> CLOB,
--                VARCHAR -> VARCHAR2.
-- =====================================================================


-- =====================================================================
-- 0. READABLE NUMBER COUNTERS
-- One row per kind of readable number. The app increments current_value
-- with a single UPDATE and formats prefix + zero-padded value, so a
-- number is never reused, even after the record is deleted.
-- =====================================================================

CREATE TABLE id_sequences (
    name        VARCHAR(40)  NOT NULL PRIMARY KEY,     -- CLIENT, CASE, DOCUMENT, ACCOUNT_STAFF, ...
    prefix      VARCHAR(10)  NOT NULL,                 -- CLI-, FLI_, DOC-, ...
    width       INTEGER      NOT NULL,                 -- zero-padded digits
    current_value  INTEGER      NOT NULL DEFAULT 0,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- =====================================================================
-- 1. LOOKUP TABLES
-- Adding a role, document type, tax year, tax type, stage or account
-- kind is a single INSERT. Code compares on `code`, never on id or name.
-- Rows are retired with is_active = FALSE, never deleted.
-- =====================================================================

CREATE TABLE account_types (
    id               INTEGER      NOT NULL PRIMARY KEY,
    code             VARCHAR(30)  NOT NULL UNIQUE,      -- CLIENT, STAFF, ADMIN, HR
